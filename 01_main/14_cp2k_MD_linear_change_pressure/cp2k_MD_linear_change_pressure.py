def extract_subsys(path):
    # 定义文件路径
    file_path = path

    # 读取文件内容
    with open(file_path, 'r', encoding='utf-8') as file:
        lines = file.readlines()

    # 初始化标志变量
    in_subsys = False
    extracted_lines = []

    # 遍历每一行
    for line in lines:
        if line.strip().startswith('&SUBSYS'):
            in_subsys = True
            extracted_lines.append(line)
        elif line.strip().startswith('&END SUBSYS'):
            in_subsys = False
            extracted_lines.append(line)
        elif in_subsys:
            extracted_lines.append(line)

    # 合并提取的行
    extracted_text = ''.join(extracted_lines)

    if extracted_text:
        return extracted_text
    else:
        print('No matching text found.')

def modify_pressure(file_path, new_value):
    # 读取文件的所有行
    #匹配科学计数法表示的浮点数（如 9.4999999999999977E+05）
    float_pattern = re.compile(r'^[-+]?(\d+(\.\d*)?|\.\d+)([eE][-+]?\d+)?$') 
    
    with open(file_path, 'r', encoding='utf-8') as file:
        lines = file.readlines()

    # 修改特定行
    for i, line in enumerate(lines):
        if line.strip().startswith('PRESSURE'):
            parts = line.split()
            if len(parts) > 1 and float_pattern.match(parts[1]):
                # 假设 pressure 后面只有一个数字
                parts[1] = str(new_value)
                lines[i] = ' '.join(parts) + '\n'
                break  # 如果只需要修改第一个匹配项，可以在这里跳出循环

    # 写回文件
    with open(file_path, 'w') as file:
        file.writelines(lines)
        
